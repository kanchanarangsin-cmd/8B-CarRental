#!/usr/bin/env python3
"""Regenerate application colors from the bundled design.md.

Run from any directory: python3 tools/sync_design_colors.py
The source of truth is the Color Tokens table, not a palette copied into code.
"""
from __future__ import annotations

import colorsys
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "design.md"
CSS = ROOT / "assets/css"
TOKEN_CSS = CSS / "design_tokens.css"
previous_css = TOKEN_CSS.read_text(encoding="utf-8") if TOKEN_CSS.exists() else ""
REPORT = ROOT / "HTS2B_EVIDENCE/COLOR_SYNC_REPORT.md"
REQUIRED = [
    "color.nav", "color.primary", "color.background", "color.surface",
    "color.text.primary", "color.text.secondary", "color.border",
    "color.surface.pastel", "color.badge.background", "color.badge.text",
    "color.danger", "color.overlay",
]
NAMES = {
    "color.nav": "nav", "color.primary": "primary",
    "color.background": "background", "color.surface": "surface",
    "color.text.primary": "text", "color.text.secondary": "muted",
    "color.border": "border", "color.surface.pastel": "pastel",
    "color.badge.background": "badge-bg", "color.badge.text": "badge-text",
    "color.danger": "danger", "color.overlay": "overlay",
}
md = DESIGN.read_text(encoding="utf-8")
font_match = re.search(r"^\*\*Font Stack:\*\* (.+)$", md, re.M)
if not font_match:
    raise SystemExit("Missing Font Stack in design.md")
font_stack = ", ".join(
    f'"{part}"' if " " in part else part
    for part in re.findall(r"`([^`]+)`", font_match.group(1))
)
if not font_stack:
    raise SystemExit("Font Stack is empty in design.md")
tokens = {}
for key in REQUIRED:
    match = re.search(r"^\| \x60" + re.escape(key) + r"\x60 \| \x60([^\x60]+)\x60", md, re.M)
    if not match:
        raise SystemExit(f"Missing token in design.md: {key}")
    tokens[key] = match.group(1)
digest = hashlib.sha256(DESIGN.read_bytes()).hexdigest()
focus = {}
for key in ("focus.ring.width", "focus.ring.offset"):
    match = re.search(r"^\| \x60" + re.escape(key) + r"\x60 \| \x60([^\x60]+)\x60", md, re.M)
    if not match:
        raise SystemExit(f"Missing focus token: {key}")
    focus[key] = match.group(1)

# The component specification controls button roles as well as hex values.
for variant, token in (("Primary", "color.primary"),
                       ("Secondary", "color.surface.pastel"),
                       ("Danger", "color.danger")):
    if not re.search(r"^\| " + variant + r" \| [^\n]*\x60" + re.escape(token) + r"\x60", md, re.M):
        raise SystemExit(f"Button variant {variant} is missing {token} in design.md")

def rgb(hex_value):
    h = hex_value.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))

def role(value):
    """Classify old UI colors by their visible role; keep opacity separately."""
    r, g, b = rgb(value)
    mx, mn = max(r, g, b), min(r, g, b)
    h, s, v = colorsys.rgb_to_hsv(r/255, g/255, b/255)
    if mn >= 250:
        return "surface"
    if mx < 65:
        return "nav" if b > r * 1.12 else "text"
    if r > g * 1.34 and r > b * 1.18 and r > 115:
        return "danger"
    if v > .90 and s < .14:
        return "background"
    if v > .87 and s < .34:
        return "pastel" if b > r else "border"
    if s < .20:
        return "muted" if v < .75 else "border"
    if v < .55 and s < .42:
        return "text"
    if v < .73 and s < .65:
        return "badge-text"
    if v > .78 and s < .42:
        return "badge-bg"
    return "primary"

palette = {NAMES[k]: v for k, v in tokens.items()}
previous_palette = dict(re.findall(r"^  --([\w-]+): (#[0-9A-Fa-f]{6});$", previous_css, re.M))
previous_values = {v.lower(): name for name, v in previous_palette.items() if name in palette}
css_header = f"/* GENERATED by tools/sync_design_colors.py from design.md SHA-256 {digest}. */\n"
lines = [":root {"]
lines.append(f"  --font-design: {font_stack};")
lines.append('  --font-body: "Inter", "Prompt", Arial, sans-serif;')
lines += [f"  --{name}: {value};" for name, value in palette.items()]
lines += [f"  --hts-{name}: var(--{name});" for name in palette]
lines += [f"  --hts-focus-width: {focus['focus.ring.width']};",
          f"  --hts-focus-offset: {focus['focus.ring.offset']};",
          "  --hts-space-1: 8px;", "  --hts-space-2: 16px;",
          "  --hts-space-3: 24px;", "  --hts-space-4: 32px;", "}"]
lines += [
    "/* Bridge legacy component names to the documented palette. */",
    ":root {",
    "  --brand: var(--primary); --brand-strong: var(--primary);",
    "  --brand-deep: var(--nav); --brand-soft: var(--pastel);",
    "  --brand-soft-2: var(--background); --accent: var(--primary);",
    "  --accent-soft: var(--pastel); --bg: var(--background);",
    "  --bg-2: var(--pastel); --surface-strong: var(--surface);",
    "  --line: var(--border); --line-soft: var(--border);",
    "  --purple: var(--primary); --purple-soft: var(--pastel);",
    "  --slate: var(--text); --success: var(--badge-text);",
    "  --success-soft: var(--badge-bg); --warning: var(--badge-text);",
    "  --warning-soft: var(--badge-bg); --danger-soft: var(--badge-bg);",
    "}",
    "body, button, input, select, textarea {",
    "  font-family: var(--font-body) !important;",
    "}",
    ".analytics-page, .rentals-page {",
    "  font-family: var(--font-body);",
    "}",
    ".analytics-page *, .rentals-page * { font-family: inherit !important; }",
    ".analytics-page :is(.fa,.fa-classic,.fa-solid,.fas),",
    ".rentals-page :is(.fa,.fa-classic,.fa-solid,.fas),",
    ".analytics-page :is(.fa,.fa-classic,.fa-solid,.fas)::before,",
    ".rentals-page :is(.fa,.fa-classic,.fa-solid,.fas)::before",
    '{ font-family: "Font Awesome 6 Free" !important; font-weight: 900 !important; }',
    ".analytics-page :is(.fa-regular,.far), .rentals-page :is(.fa-regular,.far),",
    ".analytics-page :is(.fa-regular,.far)::before, .rentals-page :is(.fa-regular,.far)::before",
    '{ font-family: "Font Awesome 6 Free" !important; font-weight: 400 !important; }',
    ".analytics-page :is(.fa-brands,.fab), .rentals-page :is(.fa-brands,.fab),",
    ".analytics-page :is(.fa-brands,.fab)::before, .rentals-page :is(.fa-brands,.fab)::before",
    '{ font-family: "Font Awesome 6 Brands" !important; }',
    "/* Section 4: Edit is Primary; use one solid color, never a gradient. */",
    ".action-group .btn-edit {",
    "  background: var(--primary) !important;",
    "  background-image: none !important;",
    "  background-color: var(--primary) !important;",
    "  color: var(--surface) !important;",
    "}",
    ".action-group .btn-edit:hover, .action-group .btn-edit:focus-visible {",
    "  background: var(--primary) !important;",
    "  background-image: none !important;",
    "  background-color: var(--primary) !important;",
    "  color: var(--surface) !important;",
    "}",
]
TOKEN_CSS.write_text(css_header + "\n".join(lines) + "\n", encoding="utf-8")

# A generated color literal remains valid in Chart.js/inline JavaScript.
# CSS color properties use custom properties so a regenerated token sheet
# propagates directly. Do not touch images or the logo asset.
hex_pattern = re.compile(r"(?<![\w])#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![\w])")
rgba_pattern = re.compile(r"rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*([\d.]+))?\s*\)")
counts = {}
files = [p for p in CSS.glob("*.css") if p != TOKEN_CSS]
files += list((ROOT / "pages").glob("*.php"))
files += list((ROOT / "assets/js").glob("*.js"))
for path in sorted(files):
    original = path.read_text(encoding="utf-8")
    count = [0]
    is_css = path.suffix == ".css"
    def replace_rgba(m):
        old = "#" + "".join(f"{int(m.group(i)):02X}" for i in (1,2,3))
        if old.lower() in previous_values:
            selected = palette[previous_values[old.lower()]]
            rr, gg, bb = rgb(selected)
            opacity = m.group(4)
            return f"rgba({rr}, {gg}, {bb}, {opacity})" if opacity else f"rgb({rr}, {gg}, {bb})"
        if old.lower() in {v.lower() for v in palette.values() if v.startswith("#")}:
            return m.group()
        selected = palette[role(old)]
        rr, gg, bb = rgb(selected)
        opacity = m.group(4)
        count[0] += 1
        return f"rgba({rr}, {gg}, {bb}, {opacity})" if opacity else f"rgb({rr}, {gg}, {bb})"
    updated = rgba_pattern.sub(replace_rgba, original)
    def replace_hex(m):
        if m.group().lower() in previous_values:
            name = previous_values[m.group().lower()]
            return f"var(--{name})" if is_css else palette[name]
        if not is_css and m.group().lower() in {v.lower() for v in palette.values() if v.startswith("#")}:
            return m.group()
        selected = role(m.group())
        count[0] += 1
        return f"var(--{selected})" if is_css else palette[selected]
    updated = hex_pattern.sub(replace_hex, updated)
    # Existing CSS root declarations must themselves refer to the token sheet.
    # Avoid a self-reference for names that are also defined in :root.
    if path.name == "style.css":
        for name in palette:
            updated = re.sub(rf"(--{re.escape(name)}\s*:\s*)var\(--{re.escape(name)}\)(\s*;)",
                             rf"\1{palette[name]}\2", updated, count=1)
    if updated != original:
        path.write_text(updated, encoding="utf-8")
        counts[str(path.relative_to(ROOT))] = count[0]

# Map the existing Bootstrap class used for Edit to the documented Primary
# variant and Delete to Danger. This is a repeatable code change from Section 4.
style_path = CSS / "style.css"
style = style_path.read_text(encoding="utf-8")
for selector, background in ((".btn-primary", "primary"),
                             (".btn-warning", "primary"),
                             (".btn-danger", "danger"),
                             (".btn-secondary", "pastel")):
    pattern = re.compile(r"(" + re.escape(selector) + r"\s*\{[^}]*?background:\s*)[^;]+(!important;)", re.S)
    style, n = pattern.subn(lambda m: m.group(1) + f"var(--{background}) " + m.group(2), style, count=1)
    if n != 1:
        raise SystemExit(f"Button rule missing in style.css: {selector}")
style_path.write_text(style, encoding="utf-8")

# Existing Edit actions used Bootstrap's warning variant. Their documented
# meaning is Primary, so keep the markup aligned with the design role.
for page_name in ("cars.php", "customers.php", "employees.php"):
    page = ROOT / "pages" / page_name
    source = page.read_text(encoding="utf-8")
    target = source.replace('class="btn btn-warning btn-sm"', 'class="btn btn-primary btn-edit btn-sm"')
    target = target.replace('class="btn btn-primary btn-sm" onclick=\'edit', 'class="btn btn-primary btn-edit btn-sm" onclick=\'edit')
    target = re.sub(r'\.\./assets/css/style\.css(?:\?v=[^"]*)?', f'../assets/css/style.css?v={digest[:12]}', target)
    target = re.sub(r'\.\./assets/css/design_tokens\.css(?:\?v=[^"]*)?',
                    f'../assets/css/design_tokens.css?v={digest[:12]}', target)
    if target != source:
        page.write_text(target, encoding="utf-8")
        counts[str(page.relative_to(ROOT))] = counts.get(str(page.relative_to(ROOT)), 0) + 1

# Place the generated token sheet immediately after the original style sheet.
# Later page CSS can continue to use --hts-* aliases from this same source.
for path in sorted((ROOT / "pages").glob("*.php")):
    old = path.read_text(encoding="utf-8")
    if "design_tokens.css" not in old and '../assets/css/style.css" rel="stylesheet">' in old:
        new = old.replace('../assets/css/style.css" rel="stylesheet">',
                          '../assets/css/style.css" rel="stylesheet">\n    <link href="../assets/css/design_tokens.css" rel="stylesheet">', 1)
        path.write_text(new, encoding="utf-8")
        counts[str(path.relative_to(ROOT))] = counts.get(str(path.relative_to(ROOT)), 0) + 1

rows = "\n".join(f"| `{k}` | `{v}` | `--{NAMES[k]}` |" for k,v in tokens.items())
changes = "\n".join(f"| `{k}` | {v} |" for k,v in sorted(counts.items()))
REPORT.write_text(
    "# หลักฐานการซิงก์สีจาก design.md\n\n"
    "รันซ้ำ: `python3 tools/sync_design_colors.py` จากโฟลเดอร์ `50`\n\n"
    f"SHA-256 ของ design.md: `{digest}`\n\n"
    "สคริปต์อ่านตาราง Color Tokens และ Focus Ring จากไฟล์นี้โดยตรง "
    "ตรวจ Button Variants ใน Section 4 แล้วสร้าง `assets/css/design_tokens.css`, "
    "กำหนดปุ่มแก้ไข/ลบจาก Primary/Danger และปรับค่าสีเดิมตามบทบาทของสี "
    "ใน CSS, inline PHP และ JavaScript ของกราฟ การแมปสีเก่าที่ไม่มี token ตรงตัว "
    "เป็นกฎในฟังก์ชัน `role()` ที่เปิดตรวจได้ การรันอีกครั้งจะไม่เปลี่ยนผลลัพธ์\n\n"
    "## ที่มาของ CSS variables\n\n| Token ใน .md | ค่า | CSS variable |\n|---|---|---|\n"
    + rows + "\n\n## จำนวนรายการที่สคริปต์แก้ในรอบนี้\n\n| ไฟล์ | จำนวน |\n|---|---:|\n"
    + changes + "\n\n"
    "รอบนี้ไม่มีรายการใหม่หากโค้ดซิงก์แล้ว; จำนวนการเปลี่ยนครั้งแรกอยู่ใน "
    "`HTS2B_EVIDENCE/COLOR_SYNC_INITIAL_REPORT.md` ซึ่งบันทึกแยกไว้ก่อนขยาย 4 ส่วนงาน\n\n"
    "สีโลโก้ที่เป็น asset รูปภาพไม่ได้ถูกแก้ สถานะพิเศษที่เคยใช้สีเขียว/ส้ม "
    "ถูกจัดเข้าชุด token ที่มีใน design.md; ตรวจรูปแบบและความหมายของ badge เมื่อเปิดหน้าเว็บจริง\n",
    encoding="utf-8",
)
print(json.dumps({"source_sha256": digest, "changed": counts}, ensure_ascii=False))
